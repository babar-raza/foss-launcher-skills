#!/usr/bin/env python3
"""Generate, audit, and remove migration shims from the manifest.

Usage:
    # Dry-run preview of shims for a wave:
    PYTHONPATH=scripts/pipeline python scripts/pipeline/tools/generate_shims.py --dry-run --wave 1

    # Generate shims for a wave:
    PYTHONPATH=scripts/pipeline python scripts/pipeline/tools/generate_shims.py --wave 1 --execute

    # Generate shims for CI scope:
    PYTHONPATH=scripts/pipeline python scripts/pipeline/tools/generate_shims.py --scope ci --execute

    # Audit all shims (check referrer counts):
    PYTHONPATH=scripts/pipeline python scripts/pipeline/tools/generate_shims.py --audit

    # Remove all shims:
    PYTHONPATH=scripts/pipeline python scripts/pipeline/tools/generate_shims.py --remove-all
"""
import pathlib
import re
import sys
import yaml

MANIFEST_PATH = pathlib.Path("scripts/pipeline/migration_manifest.yaml")

# Wave-to-domain mapping
WAVE_DOMAINS = {
    1: ["lib"],
    2: [],  # config only, no shims
    3: ["governance"],
    4: ["content"],
    5: ["knowledge"],
    6: ["ops"],
    7: ["healing", "launch", "diagnostics", "migration", "kilocode"],
    8: ["ci-checks", "ci-hooks"],
    9: ["gap-eval-src"],
}


def load_manifest():
    """Load the migration manifest."""
    return yaml.safe_load(MANIFEST_PATH.read_text(encoding="utf-8"))


def generate_entry_shim(old_path, new_path):
    """Generate a runpy-based entry-point shim."""
    return f'''#!/usr/bin/env python3
"""Migration shim — delegates to canonical location.

AUTO-GENERATED by generate_shims.py. Do not edit.
Canonical: {new_path}
"""
import runpy
import sys
from pathlib import Path

canonical = Path(__file__).resolve().parent / "{'/'.join(new_path.split('/')[2:])}"
sys.argv[0] = str(canonical)
runpy.run_path(str(canonical), run_name="__main__")
'''


def _find_underscore_imports(module_name):
    """Find underscore-prefixed names imported from module_name by other files."""
    import ast
    underscore_names = set()
    root = pathlib.Path("scripts/pipeline")
    for py in root.rglob("*.py"):
        rel = str(py).replace("\\", "/")
        if "__pycache__" in rel or "/lib/" in rel:
            continue
        if py.name == f"{module_name}.py" and py.parent == root:
            continue
        try:
            tree = ast.parse(py.read_text(encoding="utf-8", errors="replace"))
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module == module_name:
                for alias in node.names:
                    if alias.name.startswith("_") and not alias.name.startswith("__"):
                        underscore_names.add(alias.name)
    return sorted(underscore_names)


def generate_library_shim(old_path, new_path, module_name):
    """Generate a re-export library shim.

    Uses sys.modules aliasing so that `import {module}` returns the real
    lib.{module} object.  This preserves monkey-patching semantics (tests
    that do `patch.object(mod, 'ATTR', ...)` affect the real module).
    """
    parts = new_path.replace("scripts/pipeline/", "").replace(".py", "").replace("/", ".")
    return f'''"""Migration shim — re-exports from canonical location.

AUTO-GENERATED by generate_shims.py. Do not edit.
Canonical: {new_path}
"""
import importlib, sys
_real = importlib.import_module("{parts}")
sys.modules[__name__] = _real
'''


def generate_ci_py_shim(old_path, new_path):
    """Generate a CI Python validator shim."""
    return f'''#!/usr/bin/env python3
"""Migration shim — delegates to canonical location.

AUTO-GENERATED by generate_shims.py. Do not edit.
Canonical: {new_path}
"""
import runpy
import sys
from pathlib import Path

canonical = Path(__file__).resolve().parent / "{'/'.join(new_path.split('/')[2:])}"
sys.argv[0] = str(canonical)
runpy.run_path(str(canonical), run_name="__main__")
'''


def generate_ci_sh_shim(old_path, new_path):
    """Generate a CI Bash hook shim."""
    rel_from_ci = "/".join(new_path.split("/")[2:])  # e.g., hooks/simulate_pr_checks.sh
    return f'''#!/usr/bin/env bash
# Migration shim — delegates to canonical location.
# AUTO-GENERATED by generate_shims.py. Do not edit.
# Canonical: {new_path}
DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
exec "$DIR/{rel_from_ci}" "$@"
'''


def get_wave_files(manifest, wave):
    """Get files that should be shimmed for a given wave."""
    domains = WAVE_DOMAINS.get(wave, [])
    files = {}
    for path, entry in manifest["files"].items():
        if entry.get("domain") in domains and not entry.get("in_subdir") and entry.get("target") != path:
            files[path] = entry
    return files


def get_scope_files(manifest, scope):
    """Get files for a given scope (ci, gap-eval)."""
    prefix = f"scripts/{scope}/"
    files = {}
    for path, entry in manifest["files"].items():
        if path.startswith(prefix) and not entry.get("in_subdir") and entry.get("target") != path:
            files[path] = entry
    return files


def generate_shim_content(old_path, entry):
    """Generate appropriate shim content based on classification."""
    new_path = entry["target"]
    cls = entry["classification"]

    if cls == "library":
        module_name = pathlib.Path(old_path).stem
        return generate_library_shim(old_path, new_path, module_name)
    elif cls in ("entrypoint", "dual-use"):
        if old_path.endswith(".sh"):
            return generate_ci_sh_shim(old_path, new_path)
        return generate_entry_shim(old_path, new_path)
    elif cls == "ci-check":
        return generate_ci_py_shim(old_path, new_path)
    elif cls == "ci-hook":
        return generate_ci_sh_shim(old_path, new_path)
    else:
        return generate_entry_shim(old_path, new_path)


def cmd_generate(args, manifest):
    """Generate shims for a wave or scope."""
    if args.wave:
        files = get_wave_files(manifest, args.wave)
        label = f"wave {args.wave}"
    elif args.scope:
        files = get_scope_files(manifest, args.scope)
        label = f"scope {args.scope}"
    else:
        print("ERROR: Specify --wave N or --scope NAME")
        return 1

    if not files:
        print(f"No files to shim for {label}")
        return 0

    print(f"Shims for {label}: {len(files)} files")
    for old_path, entry in sorted(files.items()):
        content = generate_shim_content(old_path, entry)
        p = pathlib.Path(old_path)
        if args.dry_run:
            print(f"  [DRY-RUN] Would write shim: {old_path}")
            if args.out_dir:
                out = pathlib.Path(args.out_dir) / p.name
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(content, encoding="utf-8")
        elif args.execute:
            p.write_text(content, encoding="utf-8")
            if old_path.endswith(".sh"):
                p.chmod(p.stat().st_mode | 0o111)
            print(f"  Written: {old_path} -> {entry['target']}")
        else:
            print(f"  {old_path} -> {entry['target']}")

    return 0


def cmd_audit(manifest):
    """Audit all shims — check which still have referrers."""
    pat = re.compile(r"scripts/[a-zA-Z0-9_./-]+\.(?:py|sh)")
    shim_files = {
        path: entry for path, entry in manifest["files"].items()
        if not entry.get("in_subdir") and entry.get("target") != path
        and entry.get("shim_status") != "NOT_NEEDED"
    }

    for path, entry in sorted(shim_files.items()):
        p = pathlib.Path(path)
        is_shim = p.exists() and "AUTO-GENERATED" in p.read_text(encoding="utf-8", errors="replace")[:200]
        status = "SHIM" if is_shim else "ORIGINAL"
        print(f"  {status}: {path} (target: {entry['target']}, refs: {entry.get('external_ref_count', '?')})")

    print(f"\nTotal shimable files: {len(shim_files)}")
    return 0


def cmd_remove_all(manifest):
    """Remove all shim files."""
    removed = 0
    for path, entry in manifest["files"].items():
        if entry.get("in_subdir") or entry.get("target") == path:
            continue
        p = pathlib.Path(path)
        if p.exists():
            text = p.read_text(encoding="utf-8", errors="replace")[:200]
            if "AUTO-GENERATED" in text:
                p.unlink()
                removed += 1
                print(f"  Removed: {path}")
    print(f"\nRemoved {removed} shim files")
    return 0


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="Generate migration shims")
    parser.add_argument("--wave", type=int, help="Wave number (1-9)")
    parser.add_argument("--scope", help="Scope name (ci, gap-eval)")
    parser.add_argument("--dry-run", action="store_true", help="Preview without writing")
    parser.add_argument("--execute", action="store_true", help="Actually write shim files")
    parser.add_argument("--out-dir", help="Output directory for dry-run preview")
    parser.add_argument("--audit", action="store_true", help="Audit all shims")
    parser.add_argument("--remove-all", action="store_true", help="Remove all shim files")
    args = parser.parse_args()

    manifest = load_manifest()

    if args.audit:
        sys.exit(cmd_audit(manifest))
    elif args.remove_all:
        sys.exit(cmd_remove_all(manifest))
    else:
        sys.exit(cmd_generate(args, manifest))

"""
master_plan_index.py — Step 8 (production concurrency redesign, 2026-08-01):
FileLock-guarded upsert for plans/master-plan.md's mission index table.

CONTRACT: scripts/pipeline/lib/master_plan_index.py
  purpose: Step 6 split plans/master-plan.md into plans/missions/{mission_id}.md
           (one file per mission, removing the common cross-mission contention
           case structurally) and left master-plan.md as a thin index (mission_id
           -> file -> one-line status). That split, on its own, introduced a NEW
           and more frequent shared-write surface than the case it removed:
           prompt4-close-task.md's own updated instructions require EVERY mission
           close to update that mission's one row in the shared index -- not a
           rare hardening pass, a routine operation. Two sessions closing two
           DIFFERENT missions at the same moment is a classic lost-update race
           without a lock: both read the index, both write back their own
           snapshot, whichever writes second silently erases the other's row.
  primitive choice: advisory_lock.FileLock, NOT a TTL/heartbeat lock. Reading,
           upserting one row, and writing back is a single quick read-modify-
           write within one process call -- never held across multiple agent
           tool calls -- so FileLock (matched, per this redesign's own stated
           principle, to what it protects) is correct here. A TTL/heartbeat
           lock (the shape Step 8 originally proposed, for a rare multi-FILE
           hardening pass touching several missions' CONTENT at once) would be
           the wrong, over-heavy primitive for this narrower, more common,
           single-row operation.
  no CAS needed: unlike taskcard_store.py's update_taskcard_status (Step 5),
           this has no expected-status parameter. There is no legitimate
           scenario where two sessions race to update the SAME mission's row
           at the same instant (one mission has one governing session at a
           time, already enforced elsewhere in this redesign -- session_ledger.py,
           skill_context.py). The risk this module closes is strictly
           cross-mission: concurrent writers touching DIFFERENT rows of one
           shared file.
  format: the index table is a 3-column markdown table
           ("| Mission ID | File | Status |"), one row per mission, generated by
           this redesign's Step 6 migration. upsert_mission_row() updates an
           existing mission's row in place (preserving row order) or appends a
           new row if the mission has no row yet.

Usage::

    from master_plan_index import upsert_mission_row

    upsert_mission_row(
        "plans/master-plan.md", "MT020-2026-08-02-EXAMPLE",
        "plans/missions/MT020-2026-08-02-EXAMPLE.md", "**CLOSED**",
    )
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

_LIB_DIR = Path(__file__).resolve().parent
if str(_LIB_DIR) not in sys.path:
    sys.path.insert(0, str(_LIB_DIR))

from advisory_lock import FileLock, LockTimeout  # noqa: E402

_STALE_LOCK_SECONDS = 120.0
_DEFAULT_LOCK_TIMEOUT = 10.0
_LOCK_POLL_INTERVAL = 0.05

# Matches one data row of the index table:
#   | MT004-2026-07-16-PDF-NET-REFRESH | [plans/missions/MT004-...md](plans/missions/MT004-...md) | **CLOSED** |
_ROW_RE = re.compile(
    r"^\| (?P<id>[^\|]+?) \| \[[^\]]*\]\([^\)]*\) \| (?P<status>[^\|]*) \|\s*$",
    re.MULTILINE,
)
_HEADER_SEPARATOR_RE = re.compile(r"^\|[\s\-\|]+\|\s*$", re.MULTILINE)


class MasterPlanIndexLockTimeout(Exception):
    """Raised when the index file's lock could not be acquired within the timeout."""


def _lock(path: Path, timeout: "float | None" = None) -> FileLock:
    return FileLock(
        str(path) + ".lock",
        stale_seconds=_STALE_LOCK_SECONDS,
        timeout=timeout if timeout is not None else _DEFAULT_LOCK_TIMEOUT,
        poll=_LOCK_POLL_INTERVAL,
    )


def _make_row(mission_id: str, rel_path: str, status: str) -> str:
    return f"| {mission_id} | [{rel_path}]({rel_path}) | {status} |"


def upsert_mission_row(
    index_path: "Path | str",
    mission_id: str,
    rel_path: str,
    status: str,
    *,
    timeout: "float | None" = None,
) -> bool:
    """Insert or update mission_id's row in the index table at index_path.

    Reloads the file fresh UNDER the lock (never trusts a caller's possibly-
    stale snapshot), so a concurrent writer updating a DIFFERENT mission's row
    is never silently lost to a last-write-wins race.

    Returns True if a new row was appended, False if an existing row was
    updated in place (row order preserved).

    Raises MasterPlanIndexLockTimeout if the lock cannot be acquired within
    the timeout, ValueError if index_path doesn't exist or has no table to
    upsert into (this module updates an existing index; it does not
    scaffold a brand-new one).
    """
    path = Path(index_path)
    lock = _lock(path, timeout)
    try:
        lock.acquire()
    except LockTimeout as exc:
        raise MasterPlanIndexLockTimeout(str(exc)) from exc

    try:
        if not path.is_file():
            raise ValueError(f"index file not found: {path}")
        text = path.read_text(encoding="utf-8")

        new_row = _make_row(mission_id, rel_path, status)
        row_prefix = f"| {mission_id} | "

        lines = text.splitlines(keepends=True)
        for i, line in enumerate(lines):
            if line.startswith(row_prefix) and _ROW_RE.match(line.rstrip("\n")):
                newline = "\n" if line.endswith("\n") else ""
                lines[i] = new_row + newline
                path.write_text("".join(lines), encoding="utf-8")
                return False

        # No existing row -- append after the last matched data row (or after
        # the header separator if the table is otherwise empty).
        last_row_idx = None
        for i, line in enumerate(lines):
            if _ROW_RE.match(line.rstrip("\n")):
                last_row_idx = i
        if last_row_idx is not None:
            insert_at = last_row_idx + 1
        else:
            sep_idx = None
            for i, line in enumerate(lines):
                if _HEADER_SEPARATOR_RE.match(line.rstrip("\n")):
                    sep_idx = i
            if sep_idx is None:
                raise ValueError(f"no index table found in {path}")
            insert_at = sep_idx + 1

        lines.insert(insert_at, new_row + "\n")
        path.write_text("".join(lines), encoding="utf-8")
        return True
    finally:
        lock.release()

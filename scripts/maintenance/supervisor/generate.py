"""
generate.py — Generate next sprint prompt and HANDOFF.md draft from action list.

Reads compare output, selects the highest-priority action, reads backlog/ read-only,
and writes sprint prompt to reports/supervisor/next-sprint-{run_id}.md.

In dry-run mode (default): does NOT write backlog/HANDOFF.md.
In execute mode (--execute): may write backlog/HANDOFF.md (MODE 5 only).

Skill chains are marked needs_skill_contract_discovery when not verified from repo docs.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))
from _common import REPO_ROOT, base_args, safe_emit, is_forbidden


SPRINT_TEMPLATE = """\
# Supervisor-Generated Sprint Prompt
Generated: {timestamp}
Supervisor run: {run_id}
Dry-run mode: {dry_run}

## Selected Action
Type: {action_type}
Priority: {priority}
Reason: {reason}

## Target
{target_info}

## Suggested Skill Chain
{skill_chain_note}

{skill_chain}

## Backlog Context (read-only)
{backlog_context}

## Evidence Expected
{evidence_expected}

---
NOTE: Generated by Local Supervisor Control Plane (deterministic, no LLM).
Skill chains marked needs_skill_contract_discovery require operator verification.
Do not invoke skills in execute mode without reviewing this prompt.
"""


def _format_target(action):
    atype = action.get("type", "")
    if atype in ("REFRESH_PRODUCT", "INVESTIGATE_MISSING_STATE"):
        return f"Family: {action.get('family', 'unknown')}\nPlatform: {action.get('platform', 'unknown')}"
    if atype in ("HEAL_PAGES", "ENRICH_PAGES"):
        count = action.get("count", 0)
        sample = [p.get("path", "?") for p in action.get("pages", [])[:3]]
        return f"Page count: {count}\nSample: {sample}"
    if atype == "NO_ACTIONS_READY":
        return "No actions required — repo state is fresh."
    return f"Action: {atype}"


def generate(action_plan, dry_run=True, repo_root=None):
    root = Path(repo_root or REPO_ROOT)
    now = datetime.now(timezone.utc)
    run_id = now.strftime("%Y%m%d-%H%M%S")

    actions = action_plan.get("actions", [])
    status = action_plan.get("status", "UNKNOWN")

    if not actions or status == "NO_ACTIONS_READY":
        selected = {"type": "NO_ACTIONS_READY", "priority": 99,
                    "reason": "repo is fresh — no stale products or pages needing heal"}
    else:
        selected = actions[0]

    atype = selected.get("type", "UNKNOWN")
    skill_chain = selected.get("suggested_skills", [])
    skill_chain_str = "\n".join(f"  {s}" for s in skill_chain) if skill_chain else "  (none identified)"

    skill_chain_note = (
        "NOTE: Skills below are suggested from discovery only (needs_skill_contract_discovery).\n"
        "Verify skill syntax in AGENTS.md before invoking in execute mode."
        if selected.get("skill_chain") == "needs_skill_contract_discovery"
        else "Skills verified from repo docs."
    )

    # Read backlog context read-only
    backlog_path = root / "backlog" / "BACKLOG.md"
    if backlog_path.exists():
        try:
            lines = backlog_path.read_text(encoding="utf-8").splitlines()
            active_lines = []
            in_active = False
            for line in lines:
                if line.startswith("## Active"):
                    in_active = True
                elif line.startswith("## ") and in_active:
                    break
                elif in_active:
                    active_lines.append(line)
            backlog_context = "\n".join(active_lines[:15]) or "(Active section empty)"
        except Exception as exc:
            backlog_context = f"(Could not read backlog: {exc})"
    else:
        backlog_context = "(backlog/BACKLOG.md not found — using supervisor priority)"

    evidence_expected = (
        f"  - reports/supervisor/run-{run_id}.json\n"
        f"  - reports/supervisor/next-sprint-{run_id}.md"
    )

    prompt = SPRINT_TEMPLATE.format(
        timestamp=now.isoformat(),
        run_id=run_id,
        dry_run=dry_run,
        action_type=atype,
        priority=selected.get("priority", "?"),
        reason=selected.get("reason", ""),
        target_info=_format_target(selected),
        skill_chain_note=skill_chain_note,
        skill_chain=skill_chain_str,
        backlog_context=backlog_context,
        evidence_expected=evidence_expected,
    )

    return {
        "status": "GENERATE_COMPLETE",
        "run_id": run_id,
        "selected_action_type": atype,
        "selected_action": selected,
        "prompt": prompt,
        "prompt_path": f"reports/supervisor/next-sprint-{run_id}.md",
        "handoff_write_mode": "dry_run_skipped" if dry_run else "execute_pending",
    }


def main():
    parser = base_args("Generate sprint prompt from action list")
    parser.add_argument("--action-plan", required=True, help="Path to compare output JSON")
    args = parser.parse_args()

    try:
        action_plan = json.loads(Path(args.action_plan).read_text(encoding="utf-8"))
    except Exception as exc:
        print(f"FATAL: Could not load action plan: {exc}", file=sys.stderr)
        return 1

    dry_run = not args.execute
    data = generate(action_plan, dry_run=dry_run)

    # Write sprint prompt to reports/supervisor/ (always allowed)
    reports_sup = Path(REPO_ROOT) / "reports" / "supervisor"
    reports_sup.mkdir(parents=True, exist_ok=True)
    prompt_path = reports_sup / f"next-sprint-{data['run_id']}.md"
    prompt_path.write_text(data["prompt"], encoding="utf-8")

    # Write evidence copy if --output specified
    if args.output:
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        Path(args.output).write_text(data["prompt"], encoding="utf-8")

    result = {k: v for k, v in data.items() if k != "prompt"}
    result["prompt_written_to"] = str(prompt_path)
    print(json.dumps(result, indent=2, default=str))
    return 0


if __name__ == "__main__":
    sys.exit(main())

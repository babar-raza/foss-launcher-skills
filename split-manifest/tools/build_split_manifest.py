#!/usr/bin/env python3
"""Build the split-manifest/ folder of the replica (plan decision D4).

Inputs : the S1 evidence folder (hashes.json, report.md, transferred.tsv,
         not-transferred.tsv, stays.rules.tsv) and an additions.tsv listing
         the files the replica carries beyond the extract.
Outputs: OUTDIR/{MANIFEST.md, manifest.json, transferred.tsv,
         not-transferred.tsv, stays.rules.tsv, additions.tsv}.

Deterministic: the data files hold no timestamps; the same inputs give the same
bytes. The only date is the one in the MANIFEST.md change log, which is passed
on the command line (--date) or kept from an existing OUTDIR/MANIFEST.md.
Re-running with --additions pointing at OUTDIR/additions.tsv is idempotent.

Exit: 0 built, 1 inputs inconsistent (nothing written), 2 tool error.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

SCHEMA_VERSION = 1
PREFIX = "split-manifest/"
MANIFEST_FILES = ["MANIFEST.md", "additions.tsv", "manifest.json",
                  "not-transferred.tsv", "stays.rules.tsv", "transferred.tsv"]
COPIED = ["transferred.tsv", "not-transferred.tsv", "stays.rules.tsv"]
HEADERS = {
    "transferred.tsv": ["path", "bucket", "rule"],
    "not-transferred.tsv": ["path", "bucket", "rule", "reason"],
    "stays.rules.tsv": ["bucket", "rule", "files", "top_level"],
    "additions.tsv": ["path", "reason", "source"],
}
HEX64 = re.compile(r"^[0-9a-f]{64}$")
HEX40 = re.compile(r"^[0-9a-f]{40}$")
POLICY_RE = re.compile(r"policy:\s*`[^`]*`\s*sha256\s*`([0-9a-f]{64})`")
LOG_HEAD = "## Change log"


class ManifestError(Exception):
    """The inputs are inconsistent (exit 1)."""


def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def paths_sha256(paths):
    return sha256_bytes(("\n".join(sorted(paths)) + "\n").encode("utf-8"))


def read_tsv(path, name):
    data = Path(path).read_bytes()
    if b"\r" in data:
        raise ManifestError(f"{name}: contains CR characters (LF only)")
    text = data.decode("utf-8")
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    header = HEADERS[name]
    if not lines or lines[0].split("\t") != header:
        raise ManifestError(f"{name}: header is not {header}")
    rows = []
    for n, line in enumerate(lines[1:], start=2):
        cols = line.split("\t")
        if len(cols) != len(header):
            raise ManifestError(f"{name}:{n}: expected {len(header)} columns, got {len(cols)}")
        rows.append(cols)
    return rows, data


def dup_paths(paths):
    seen, dups = set(), []
    for p in paths:
        if p in seen:
            dups.append(p)
        seen.add(p)
    return dups


def bad_path(p):
    return (not p or p.startswith("/") or "\\" in p or p.endswith("/")
            or any(seg in ("", ".", "..") for seg in p.split("/")))


def count_by(rows, idx):
    out = {}
    for r in rows:
        out[r[idx]] = out.get(r[idx], 0) + 1
    return dict(sorted(out.items()))


def load_evidence(ev):
    ev = Path(ev)
    tr, tr_b = read_tsv(ev / "transferred.tsv", "transferred.tsv")
    nt, nt_b = read_tsv(ev / "not-transferred.tsv", "not-transferred.tsv")
    st, st_b = read_tsv(ev / "stays.rules.tsv", "stays.rules.tsv")
    hashes = json.loads((ev / "hashes.json").read_text(encoding="utf-8"))
    m = POLICY_RE.search((ev / "report.md").read_text(encoding="utf-8"))
    if not m:
        raise ManifestError("report.md: policy sha256 line not found")
    return {"tr": tr, "nt": nt, "st": st, "hashes": hashes, "policy": m.group(1),
            "bytes": {"transferred.tsv": tr_b, "not-transferred.tsv": nt_b,
                      "stays.rules.tsv": st_b}}


def manifest_rows():
    gen = "generated by split-manifest/tools/build_split_manifest.py"
    why = {
        "MANIFEST.md": "split manifest: human summary and change log",
        "additions.tsv": "split manifest: files the replica carries beyond the extract",
        "manifest.json": "split manifest: machine-readable counts and hashes",
        "not-transferred.tsv": "split manifest: paths of the base commit that are not transferred",
        "stays.rules.tsv": "split manifest: rules for the paths that stay in aspose.org",
        "transferred.tsv": "split manifest: paths transferred from aspose.org",
    }
    src = {"MANIFEST.md": gen, "additions.tsv": gen, "manifest.json": gen,
           "not-transferred.tsv": "copy of the S1 evidence file not-transferred.tsv",
           "stays.rules.tsv": "copy of the S1 evidence file stays.rules.tsv",
           "transferred.tsv": "copy of the S1 evidence file transferred.tsv"}
    return [[PREFIX + n, why[n], src[n]] for n in MANIFEST_FILES]


def merge_additions(input_rows):
    generated = {PREFIX + n for n in MANIFEST_FILES}
    rows = [r for r in input_rows if r[0] not in generated] + manifest_rows()
    return sorted(rows, key=lambda r: r[0].encode("utf-8"))


def check_inputs(ev, rows, hashes_ok=True):
    problems = []
    tp = [r[0] for r in ev["tr"]]
    np_ = [r[0] for r in ev["nt"]]
    ap = [r[0] for r in rows]
    for label, lst in (("transferred", tp), ("not-transferred", np_), ("additions", ap)):
        d = dup_paths(lst)
        if d:
            problems.append(f"duplicate paths in {label}: {d[:20]}")
        b = [p for p in lst if bad_path(p)]
        if b:
            problems.append(f"malformed paths in {label}: {b[:20]}")
    for la, a, lb, b in (("transferred", tp, "not-transferred", np_),
                         ("additions", ap, "transferred", tp),
                         ("additions", ap, "not-transferred", np_)):
        both = sorted(set(a) & set(b))
        if both:
            problems.append(f"{len(both)} path(s) in both {la} and {lb}: {both[:20]}")
    h = ev["hashes"]
    stays = sum(int(r[2]) for r in ev["st"])
    if hashes_ok:
        for key, val in (("moved", len(tp)), ("excluded", len(np_)), ("stays", stays),
                         ("universe", len(tp) + len(np_) + stays),
                         ("moveset_sha256", paths_sha256(tp)),
                         ("excluded_sha256", paths_sha256(np_))):
            if h.get(key) != val:
                problems.append(f"hashes.json {key}={h.get(key)!r} but recomputed {val!r}")
        if not HEX40.match(str(h.get("base", ""))) or not HEX40.match(str(h.get("base_tree", ""))):
            problems.append("hashes.json: base/base_tree is not a 40-hex id")
        if not HEX64.match(str(h.get("stays_sha256", ""))):
            problems.append("hashes.json: stays_sha256 is not 64-hex")
    return problems


def build_manifest_json(ev, rows, file_hashes):
    h = ev["hashes"]
    tr_n, nt_n = len(ev["tr"]), len(ev["nt"])
    stays = sum(int(r[2]) for r in ev["st"])
    return {
        "schema_version": SCHEMA_VERSION,
        "base": {"commit": h["base"], "tree": h["base_tree"]},
        "counts": {"universe": tr_n + nt_n + stays, "moved": tr_n, "excluded": nt_n,
                   "stays": stays, "additions": len(rows), "replica_files": tr_n + len(rows)},
        "buckets": {"moved": count_by(ev["tr"], 1), "excluded": count_by(ev["nt"], 1),
                    "stays": {"R": stays}},
        "hashes": {"moveset_sha256": paths_sha256([r[0] for r in ev["tr"]]),
                   "excluded_sha256": paths_sha256([r[0] for r in ev["nt"]]),
                   "stays_sha256": h["stays_sha256"], "policy_sha256": ev["policy"]},
        "files": file_hashes,
    }


def render_md(mj, log_lines):
    c, b, hs = mj["counts"], mj["buckets"], mj["hashes"]

    def split(d):
        return ", ".join(f"{k} {v:,}" for k, v in d.items())

    out = [
        "# Split manifest",
        "",
        "What this repository received from the aspose.org monorepo, and what it did not.",
        "Generated by `split-manifest/tools/build_split_manifest.py`; checked by",
        "`split-manifest/tools/verify_split_manifest.py`. Do not edit by hand except the change log.",
        "",
        f"- Base commit: `{mj['base']['commit']}` (aspose.org)",
        f"- Base tree: `{mj['base']['tree']}`",
        f"- Policy (split-policy) sha256: `{hs['policy_sha256']}`",
        "",
        "## Counts",
        "",
        "| Group | Paths | Buckets |",
        "|---|---:|---|",
        f"| Tracked paths at the base commit (universe) | {c['universe']:,} | |",
        f"| Transferred (`transferred.tsv`) | {c['moved']:,} | {split(b['moved'])} |",
        f"| Not transferred, excluded on purpose (`not-transferred.tsv`) | {c['excluded']:,} | {split(b['excluded'])} |",
        f"| Stay in aspose.org (`stays.rules.tsv`, summarised by rule) | {c['stays']:,} | {split(b['stays'])} |",
        f"| Added by the replica, not from the extract (`additions.tsv`) | {c['additions']:,} | |",
        f"| Files in the replica tree (transferred + additions) | {c['replica_files']:,} | |",
        "",
        "Transferred + not transferred + stays = universe.",
        "",
        "## Rules",
        "",
        "Every path of the base commit is classified once by split-policy. Bucket R (site content, themes,",
        "static files, layouts, configs, site data) stays in aspose.org and is listed only by rule, because",
        "its content is the website. Buckets M (tooling), A (archive and one-off material) and S (stubs) move,",
        "except 20 aspose.org CI workflows (`.github/workflows/*`) which would start running on this public",
        "repository; those are listed in `not-transferred.tsv` with the reason. Nothing is deleted from",
        "aspose.org. The replica tree must equal transferred.tsv paths plus additions.tsv paths exactly.",
        "",
        "## Files",
        "",
        "- `transferred.tsv`: path, bucket, rule. One row per path present in the replica from the extract.",
        "- `not-transferred.tsv`: path, bucket, rule, reason. Paths of the base commit deliberately left out.",
        "- `stays.rules.tsv`: bucket, rule, files, top_level. The paths that stay, summarised by rule.",
        "- `additions.tsv`: path, reason, source. Files that exist here but were not extracted (includes this folder).",
        "- `manifest.json`: counts, bucket counts, sha256 values; the verifier recomputes them.",
        "- `tools/`: `build_split_manifest.py`, `verify_split_manifest.py` and their tests.",
        "",
        "## Regenerate and verify",
        "",
        "```",
        "<python> split-manifest/tools/build_split_manifest.py --evidence EVIDENCE_DIR --additions split-manifest/additions.tsv --out split-manifest [--log-entry TEXT --date YYYY-MM-DD]",
        "<python> split-manifest/tools/verify_split_manifest.py --repo . --ref HEAD --manifest-dir split-manifest [--base-commit SHA]",
        "```",
        "",
        "`EVIDENCE_DIR` is the S1 evidence folder of the split plan (hashes.json, report.md and the three TSV files).",
        "Run the tests with `<python> -m pytest split-manifest/tools`.",
        "",
        LOG_HEAD,
        "",
    ]
    return "\n".join(out + log_lines) + "\n"


def existing_log(md_path):
    if not md_path.exists():
        return []
    text = md_path.read_text(encoding="utf-8")
    if LOG_HEAD not in text:
        return []
    tail = text.split(LOG_HEAD, 1)[1].strip("\n")
    return [ln for ln in tail.split("\n") if ln.strip()]


def build(evidence, additions, out, date=None, log_entry=None, staging_root=None, validate=True):
    evidence, out = Path(evidence), Path(out)
    if evidence.resolve() == out.resolve():
        raise ManifestError("--out must differ from --evidence")
    ev = load_evidence(evidence)
    in_rows, _ = read_tsv(additions, "additions.tsv")
    rows = merge_additions(in_rows)
    problems = check_inputs(ev, rows, hashes_ok=validate)
    if staging_root is not None:
        for r in rows:
            if not (Path(staging_root) / r[0]).exists() and r[0] not in {PREFIX + n for n in MANIFEST_FILES}:
                problems.append(f"additions.tsv lists {r[0]} but it is not under the staging root")
    if problems:
        raise ManifestError("\n".join(problems))
    out.mkdir(parents=True, exist_ok=True)
    log = existing_log(out / "MANIFEST.md")
    mj0 = build_manifest_json(ev, rows, {})
    default_entry = (f"Created. Base {mj0['base']['commit'][:12]}; {mj0['counts']['moved']} paths transferred, "
                     f"{mj0['counts']['excluded']} not transferred, {mj0['counts']['stays']} stay in aspose.org, "
                     f"{mj0['counts']['additions']} replica additions (this folder included).")
    new_entries = []
    if not log:
        new_entries.append(default_entry)
    if log_entry:
        new_entries.append(log_entry)
    for e in new_entries:
        if date is None:
            raise ManifestError("--date is required when a change log entry is added")
        line = f"- {date}: {e}"
        if line not in log:
            log.append(line)
    add_bytes = ("\t".join(HEADERS["additions.tsv"]) + "\n"
                 + "".join("\t".join(r) + "\n" for r in rows)).encode("utf-8")
    fh = {n: sha256_bytes(ev["bytes"][n]) for n in COPIED}
    fh["additions.tsv"] = sha256_bytes(add_bytes)
    mj = build_manifest_json(ev, rows, dict(sorted(fh.items())))
    for n in COPIED:
        (out / n).write_bytes(ev["bytes"][n])
    (out / "additions.tsv").write_bytes(add_bytes)
    (out / "manifest.json").write_bytes((json.dumps(mj, indent=1, sort_keys=True) + "\n").encode("utf-8"))
    (out / "MANIFEST.md").write_bytes(render_md(mj, log).encode("utf-8"))
    return mj


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--evidence", required=True, help="S1 evidence directory")
    ap.add_argument("--additions", required=True, help="additions.tsv (path, reason, source)")
    ap.add_argument("--out", required=True, help="output directory (split-manifest/)")
    ap.add_argument("--date", help="date for new change log entries (YYYY-MM-DD)")
    ap.add_argument("--log-entry", help="extra change log entry text")
    ap.add_argument("--staging-root", help="check that every non-manifest additions path exists below this directory")
    a = ap.parse_args(argv)
    try:
        mj = build(a.evidence, a.additions, a.out, a.date, a.log_entry, a.staging_root)
    except ManifestError as e:
        print(f"FAIL: {e}", file=sys.stderr)
        return 1
    except (OSError, ValueError, KeyError) as e:
        print(f"ERROR: {type(e).__name__}: {e}", file=sys.stderr)
        return 2
    c = mj["counts"]
    print(f"built {a.out}: moved {c['moved']}, excluded {c['excluded']}, stays {c['stays']}, "
          f"additions {c['additions']}, replica_files {c['replica_files']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
